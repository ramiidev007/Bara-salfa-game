package com.example.model

enum class GameMode {
  SALFA_BARRA,    // برا السالفة (Social Deduction / Impostor)
  WORD_BOMB,      // القنبلة الموقوتة (Tick Tick Boom / Fast Word Passing)
  TRUTH_OR_DARE,  // صراحة أو جرأة (Spinning Bottle / Truth or Dare)
  CHARADES        // تمثيل بدون كلام (Silent Acting / Charades)
}

data class Player(
  val id: String,
  val name: String,
  val role: String = "informed", // "informed" or "impostor"
  val votedFor: String? = null,
  val bombLives: Int = 3
)

data class Category(
  val id: String,
  val name: String,
  val icon: String,
  val words: List<String>,
  val isVip: Boolean = false
)

data class BombTopic(
  val id: String,
  val title: String,
  val icon: String,
  val description: String,
  val examples: List<String>,
  val isVip: Boolean = false
)

enum class GamePhase {
  HOME,
  PLAYER_SETUP,
  CATEGORY_SELECTION,
  PASS_AND_REVEAL,
  TIMER,
  VOTING,
  RESULT,
  
  // Word Bomb specific phases
  BOMB_TOPIC_SELECTION,
  BOMB_GAME,
  BOMB_RESULT,

  // Truth or Dare (Spinning Bottle) phases
  TOD_SPIN,
  TOD_PROMPT,

  // Charades (تمثيل بدون كلام) phases
  CHARADES_SETUP,
  CHARADES_GAME,
  CHARADES_ROUND_RESULT
}

enum class TodChoiceType {
  TRUTH,  // صراحة
  DARE    // جرأة / تحدي
}

data class TodPack(
  val id: String,
  val title: String,
  val icon: String,
  val description: String,
  val truths: List<String>,
  val dares: List<String>,
  val isVip: Boolean = false
)

data class CharadesCategory(
  val id: String,
  val name: String,
  val icon: String,
  val description: String,
  val items: List<String>,
  val isVip: Boolean = false
)

data class CharadesTeam(
  val id: String,
  val name: String,
  val colorHex: Long,
  val score: Int = 0
)

